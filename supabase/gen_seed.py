#!/usr/bin/env python3
"""Write supabase/seed.sql: the catalog ids submit_run() accepts.

Re-run after build_manifest.py adds simulations, then apply seed.sql in the
Supabase SQL editor (or `supabase db push` picks it up as seed data).
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
manifest = json.load(open(os.path.join(HERE, '..', 'player', 'manifest.json'), encoding='utf-8'))
ids = sorted({s['id'] for s in manifest['sims']}, key=lambda x: (len(x), x))
rows = ',\n'.join("  ('%s')" % i for i in ids)
with open(os.path.join(HERE, 'seed.sql'), 'w', encoding='utf-8', newline='\n') as f:
    f.write('-- Generated by supabase/gen_seed.py from player/manifest.json. Do not edit.\n')
    f.write('insert into public.known_sims (id) values\n%s\non conflict (id) do nothing;\n' % rows)
print('%d simulation ids -> supabase/seed.sql' % len(ids))
